// Helper to get crop lifespan classification and rules
export const getCropLifespanRules = (cropName = "") => {
  const name = cropName.toLowerCase();
  if (name.includes("tomato") || name.includes("chilli") || name.includes("okra") || name.includes("vegetable") || name.includes("cabbage") || name.includes("cauliflower")) {
    return {
      category: "Perishable Vegetable",
      typicalLifespanDays: "3 to 7 Days",
      inspectionWindowHours: 18,
      urgency: "Immediate (High Perishability)",
      returnTerms: "Strict 18-hour inspection upon delivery. Spoilage beyond 18 hours is buyer storage liability.",
      protectionNote: "Rapid dispute resolution with digital photo audit. Partial price markdown prioritized over physical returns to prevent rot and dumping.",
      storageRequirement: "Cold chain transit (10°C - 14°C, 85-90% RH)",
    };
  }
  if (name.includes("onion") || name.includes("potato") || name.includes("garlic") || name.includes("ginger")) {
    return {
      category: "Semi-Perishable Tuber/Bulb",
      typicalLifespanDays: "30 to 60 Days",
      inspectionWindowHours: 48,
      urgency: "Standard (Moderate Shelf Life)",
      returnTerms: "48-hour return window from delivery receipt. Max 4% sprouting and 3% rot tolerance.",
      protectionNote: "2% natural transit dehydration accepted by buyer. Certified weighbridge discrepancy > 3% triggers escrow hold.",
      storageRequirement: "Well-ventilated, moisture-free ambient shed or cold store (0°C - 2°C for potato, ambient dry for onion)",
    };
  }
  // Grains, oilseeds, fibers
  return {
    category: "Durable Agronomic Crop / Fiber",
    typicalLifespanDays: "180 to 365+ Days",
    inspectionWindowHours: 72,
    urgency: "Stable (High Storage Resilience)",
    returnTerms: "72-hour inspection window. Rejection valid only if lab moisture exceeds AGMARK threshold or trash exceeds 2.5%.",
    protectionNote: "Return invalid once bags/bales are opened for milling/ginning. Pre-certified AGMARK lots have instant dispute immunity.",
    storageRequirement: "Dry airtight warehouse / silo with moisture < 10-12%",
  };
};
